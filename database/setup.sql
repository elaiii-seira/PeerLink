-- Base tables: profiles, skills, user_skills.
-- Run this FIRST, before the other scripts in this folder.
-- Supabase > SQL Editor > New query. If the editor says "Only singular query allowed",
-- run each statement on its own, in order.
--
-- A profile row is created by the app when a student registers (the insert policy below
-- allows a signed-in user to create only their own row), so no sign-up trigger is needed.
-- After running this, import database/skills.csv into the skills table
-- (Table Editor > skills > Insert > Import data from CSV).

create table public.profiles (
  id uuid primary key default auth.uid() references auth.users (id) on update cascade on delete cascade,
  created_at timestamptz not null default now(),
  full_name text,
  course text,
  year_level text,
  bio text,
  availability text[]
);

create table public.skills (
  id bigint generated by default as identity primary key,
  name text,
  category text   -- 'academic' or 'practical'
);

create table public.user_skills (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  user_id uuid not null default auth.uid() references public.profiles (id) on update cascade on delete cascade,
  skill_id bigint not null references public.skills (id) on update cascade on delete cascade,
  type text not null   -- 'teach' or 'learn'
);

alter table public.profiles enable row level security;
alter table public.skills enable row level security;
alter table public.user_skills enable row level security;

create policy "Authenticated users can view profiles"
on public.profiles for select to authenticated
using (true);

create policy "Users can insert own profile"
on public.profiles for insert to authenticated
with check (auth.uid() = id);

create policy "Users can update own profile"
on public.profiles for update to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

create policy "Authenticated users can read skills"
on public.skills for select to authenticated
using (true);

create policy "Authenticated users can read user_skills"
on public.user_skills for select to authenticated
using (true);

create policy "Users can add own skills"
on public.user_skills for insert to authenticated
with check (auth.uid() = user_id);

create policy "Users can remove own skills"
on public.user_skills for delete to authenticated
using (auth.uid() = user_id);
